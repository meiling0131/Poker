"""Pack the trained tables (out/<scenario>.json) into js/gto-table.js, the file the bots read.

  python3 pack.py                 # every out/*.json
  python3 pack.py out/srp_ip.json out/3bp_oop.json
  python3 pack.py --clear         # an empty table: the bots go back to their own rules
  python3 pack.py --to t.json     # plain JSON instead, to try a table without shipping it (GTO_TABLE=t.json)

Each scenario keeps its bucket edges, its key list (uint16) and, for every key, ten buckets of six action
probabilities as bytes (0..255), all base64 so the module stays plain JavaScript.
"""
import base64
import glob
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, '..', '..', 'js', 'gto-table.js')
HEAD = ('// The bots\' postflop strategy table, learned by the solver in tools/solver (see its README).\n'
        '// Generated by tools/solver/pack.py; do not edit by hand. null: no table, the bots use their own rules.\n')


def pack(paths):
    scen, common = {}, None
    for path in paths:
        with open(path) as f:
            d = json.load(f)
        nb = d['nb']
        keys = sorted(int(k) for k in d['keys'])
        data = bytearray()
        for k in keys:
            rows = d['keys'][str(k)]
            for b in range(nb):
                row = rows[b] if b < len(rows) else []
                tot = sum(row) if row else 0
                data += bytes(min(255, round(x / tot * 255)) for x in row) if tot > 0 else bytes(6)
        scen[d['scenario']] = {'pot': d['pot'], 'stack': d['stack'], 'init': d['init'], 'iters': d['iters'],
                               'edges': d['edges'], 'keys': base64.b64encode(struct.pack(f'<{len(keys)}H', *keys)).decode(),
                               'data': base64.b64encode(bytes(data)).decode()}
        common = {'nb': nb, 'ehsBins': d['ehsBins'], 'potT': d['potT']}
        print(f'{d["scenario"]}: {len(keys)} keys, {d["iters"]} iterations, {len(data) // 1024} KB')
    return dict(v=1, **common, scen=scen) if scen else None


def main():
    args, target = sys.argv[1:], TARGET
    if '--to' in args:                     # --to table.json: plain JSON for tools/exploit.js (GTO_TABLE=table.json)
        i = args.index('--to')
        target = args[i + 1]
        args = args[:i] + args[i + 2:]
    paths = args or sorted(glob.glob(os.path.join(HERE, 'out', '*.json')))
    if args != ['--clear'] and not paths:
        sys.exit('no tables in tools/solver/out: train first (solve.py), or pass --clear to switch the table off')
    table = None if args == ['--clear'] else pack(paths)
    text = json.dumps(table, separators=(',', ':'))
    with open(target, 'w') as f:
        f.write(text if target.endswith('.json') else HEAD + 'export default ' + text + ';\n')
    print('wrote', os.path.normpath(target), f'({os.path.getsize(target) // 1024} KB)')


if __name__ == '__main__':
    main()
